const assert=require('node:assert/strict');
const {transformSync}=require('esbuild');
const {readFileSync}=require('node:fs');
const Module=require('node:module');
const source=transformSync(readFileSync('src/lib/reader-highlights.ts','utf8'),{loader:'ts',format:'cjs'}).code;
const moduleForTest=new Module('reader-highlights');moduleForTest._compile(source,'reader-highlights.cjs');
const {highlightRuns}=moduleForTest.exports;
const page={id:'a',content:'A😀BC DEFG',parts:[{page_id:'a',start_off:10,end_off:14,card_start:0},{page_id:'b',start_off:7,end_off:11,card_start:5}]};
const marks=[{page_id:'a',start_off:11,end_off:14},{page_id:'b',start_off:7,end_off:9},{page_id:'other',start_off:0,end_off:500}];
const runs=highlightRuns(page,marks,0,9);
assert.equal(runs.map(r=>r.text).join(''),page.content);
assert.deepEqual(runs.filter(r=>r.marked).map(r=>r.text),['😀BC','DE']);
const continuation=highlightRuns(page,marks,2,8);
assert.equal(continuation.map(r=>r.text).join(''),'BC DEF');
assert.deepEqual(continuation.filter(r=>r.marked).map(r=>r.text),['BC','DE']);
const fallback=highlightRuns({id:'a',content:'A😀BCD',start_off:10},marks,0,5);
assert.deepEqual(fallback.filter(r=>r.marked).map(r=>r.text),['😀BC']);
assert.equal(highlightRuns(undefined,marks,0,1).length,0);
console.log('Unicode source offsets, joined-page annotations, continuation clipping and source-only marks passed.');
