const assert=require('node:assert/strict');
(async()=>{
 const core=await import('../src/lib/ai-diagnostics-core.ts');
 const config={context:512,budgetMiB:768,maxTokens:32};
 assert.equal(core.validateConfig({...config,budgetMiB:2048}).budgetMiB,2048);
 assert.throws(()=>core.validateConfig({...config,budgetMiB:4096}));
 assert.deepEqual(core.validateConfig(config),config);
 assert.throws(()=>core.validateConfig({...config,context:262144}),/Unsupported/);
 let report=core.createReport(config,{standalone:true});
 report=core.recordPhase(report,'prompt-prefill','Synthetic test',true,true);
 assert.equal(core.parseReport(JSON.stringify(report)).active,true);
 assert.equal(core.parseReport(JSON.stringify(report)).resident,true);
 for(let i=0;i<300;i++)report=core.recordPhase(report,'progress','x'.repeat(1000));
 assert.equal(report.events.length,160);assert.equal(report.events.at(-1).detail.length,400);
 assert.equal(core.parseReport('broken'),null);assert.equal(core.parseReport(null),null);
 const manifest={records:[{dataPath:'params_shard_0.bin',nbytes:127139840}]};
 assert.equal(core.shardURLs(manifest)[0].url,core.DIAG_MODEL_URL+'params_shard_0.bin');
 assert.throws(()=>core.shardURLs({records:[{dataPath:'https://evil.invalid/model',nbytes:4}]}));
 assert.throws(()=>core.shardURLs({records:[{dataPath:'../model',nbytes:4}]}));
 assert.throws(()=>core.shardURLs({records:[]}));
 assert.throws(()=>core.shardURLs({records:[{dataPath:'large.bin',nbytes:170*core.MIB}]}));
 let allocations=0,destroyed=0;const updates=[];
 const device={createBuffer:()=>{allocations++;return {destroy(){destroyed++}}}};
 const stats=core.installBufferBudget(device,100,s=>updates.push(s));
 const a=device.createBuffer({size:60});
 assert.throws(()=>device.createBuffer({size:50}),/budget exceeded/);
 assert.equal(allocations,1,'over-budget request reached native GPU allocation');
 assert.equal(stats().liveBytes,60);a.destroy();a.destroy();assert.equal(stats().liveBytes,0);
 const b=device.createBuffer({size:90});assert.equal(stats().peakBytes,90);b.destroy();
 assert.equal(stats().largestBufferBytes,90);assert.equal(stats().allocatedBuffers,2);
 assert.throws(()=>device.createBuffer({size:Infinity}));assert.throws(()=>device.createBuffer({size:-1}));
 assert(core.diagnosticPrompt('card','explain','English')[1].content.length>600);
 assert.throws(()=>core.diagnosticPrompt('private-book','explain','English'));
 assert.throws(()=>core.diagnosticPrompt('short','explain','Injected language'));
 const cause=Object.assign(new Error('budget exceeded'),{code:'GPU_LIMIT'});
 const wrapped=core.diagnosticError({name:'RuntimeError',message:'GPU callback failed',cause});
 assert.equal(wrapped.message,'GPU callback failed');assert.equal(wrapped.details.cause.message,'budget exceeded');assert.equal(wrapped.details.cause.code,'GPU_LIMIT');assert(wrapped.details.cause.stack);
 const circular={message:'cyclic'};circular.cause=circular;assert.doesNotThrow(()=>JSON.stringify(core.diagnosticError(circular)));
 const noMessage=core.diagnosticError({code:17,reason:'device lost'});assert(noMessage.message.includes('device lost'));assert(!noMessage.message.includes('[object Object]'));
 const binary=core.diagnosticError({message:'error',buffer:new Uint8Array(100000)});assert.equal(binary.details.buffer,'[Binary data omitted]');
 const getter={};Object.defineProperty(getter,'message',{get(){throw new Error('getter failed')}});assert.doesNotThrow(()=>core.diagnosticError(getter));
 assert.equal(core.createReport(config,{}).recorderVersion,2);
 console.log('Diagnostic reports, GPU budget, structured errors, nested causes and bounded serialization passed');
})().catch(e=>{console.error(e);process.exit(1)});
